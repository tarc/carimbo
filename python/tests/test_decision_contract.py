"""Cross-stack contract test for decision-1 (AGT-04, D-36).

``data/contract/decision-responses/*.json`` is generated by the .NET ``DecisionGoldenResponseTests``
(``just golden``). Every file must parse with the strict models in
``carimbo_evals.decision_contract`` (``extra="forbid"``), so an added, renamed or retyped member of
the endpoint's response fails here before any run depends on it.
``data/contract/decision-request.json`` is the one hand-written file there.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pytest
from pydantic import ValidationError

from carimbo_evals.decision_contract import DecisionRequest, DecisionResponse
from carimbo_evals.runner import build_decision_payload

REPO_ROOT = Path(__file__).resolve().parents[2]
CONTRACT = REPO_ROOT / "data" / "contract"
RESPONSES = CONTRACT / "decision-responses"
REQUEST = CONTRACT / "decision-request.json"
FIXTURES = sorted(RESPONSES.glob("*.json"))
SCENARIOS = {
    "decided",
    "guard_override",
    "tool_failed",
    "step_budget_exhausted",
    "refused",
    "schema_invalid",
    "cache_hit",
    "cache_miss",
    "overrides",
}
STATUSES = {"decided", "refused", "schema_invalid", "infrastructure_failure"}
DECIDED_BY = {"model", "guard", "tool_failure", "step_budget"}


def _responses() -> dict[str, DecisionResponse]:
    return {
        path.stem: DecisionResponse.model_validate_json(path.read_text(encoding="utf-8"))
        for path in FIXTURES
    }


def _load(name: str) -> dict[str, Any]:
    loaded = json.loads((RESPONSES / name).read_text(encoding="utf-8"))
    assert isinstance(loaded, dict)
    return loaded


def test_there_are_golden_responses() -> None:
    assert FIXTURES, f"no fixtures under {RESPONSES}; run: just golden"


@pytest.mark.parametrize("path", FIXTURES, ids=lambda path: path.name)
def test_every_golden_response_parses_with_the_strict_models(path: Path) -> None:
    response = DecisionResponse.model_validate_json(path.read_text(encoding="utf-8"))

    assert response.contract_version == "decision-1"


def test_the_fixtures_are_exactly_the_scenario_set() -> None:
    assert {path.stem for path in FIXTURES} == SCENARIOS


def test_an_extra_top_level_member_is_rejected() -> None:
    body = _load("decided.json")
    body["surprise"] = 1

    with pytest.raises(ValidationError) as caught:
        DecisionResponse.model_validate_json(json.dumps(body))

    assert "surprise" in str(caught.value)


def test_an_extra_member_inside_a_step_is_rejected() -> None:
    body = _load("decided.json")
    body["steps"][0]["surprise"] = 1

    with pytest.raises(ValidationError) as caught:
        DecisionResponse.model_validate_json(json.dumps(body))

    assert "surprise" in str(caught.value)


def test_an_extra_member_inside_a_tool_call_is_rejected() -> None:
    body = _load("decided.json")
    body["steps"][0]["tool_calls"][0]["surprise"] = 1

    with pytest.raises(ValidationError) as caught:
        DecisionResponse.model_validate_json(json.dumps(body))

    assert "surprise" in str(caught.value)


def test_a_missing_member_is_rejected() -> None:
    body = _load("decided.json")
    del body["cost_usd"]

    with pytest.raises(ValidationError) as caught:
        DecisionResponse.model_validate_json(json.dumps(body))

    assert "cost_usd" in str(caught.value)


def test_the_statuses_and_deciders_across_the_fixtures_are_pinned() -> None:
    responses = _responses().values()

    assert {r.outcome.status for r in responses} == STATUSES
    assert {r.outcome.decided_by for r in responses if r.outcome.decided_by} == DECIDED_BY


def test_a_guard_override_a_tool_failure_and_an_exhausted_budget_are_pinned() -> None:
    responses = _responses()

    override = responses["guard_override"].outcome
    assert override.guard is not None
    assert override.guard.overridden is True
    assert override.model_decision is not None
    assert override.model_decision.outcome == "approve"
    assert override.decision is not None
    assert (override.decision.outcome, override.decision.cause) == (
        "escalate",
        "extraction_not_success",
    )
    failed = responses["tool_failed"].outcome
    assert failed.tool_failure is not None
    assert failed.tool_failure.error_kind == "is_error"
    assert failed.guard is None
    assert failed.decision is not None
    assert failed.decision.cause == "tool_failed"
    budget = responses["step_budget_exhausted"]
    assert budget.outcome.decision is not None
    assert budget.outcome.decision.cause == "step_budget_exhausted"
    assert len(budget.steps) == budget.effective.max_steps == 2
    assert [call.outcome for call in budget.steps[-1].tool_calls] == ["skipped"]


def test_a_cache_hit_and_a_cache_miss_are_pinned() -> None:
    responses = _responses()

    hits = [s for s in responses["cache_hit"].steps if s.cache and s.cache.status == "hit"]
    assert len(hits) == len(responses["cache_hit"].steps) == 2
    assert all(step.http_attempts == 0 for step in hits)
    assert responses["cache_hit"].incurred_cost_usd == "0.00000000"
    assert responses["cache_hit"].cost_usd not in (None, "0.00000000")
    miss = responses["cache_miss"].outcome.failure
    assert miss is not None
    assert miss.kind == "cache_miss"
    assert responses["cache_miss"].incurred_cost_usd == "0.00000000"


def test_a_refusal_and_malformed_output_have_no_decision() -> None:
    responses = _responses()

    for name, status in (("refused", "refused"), ("schema_invalid", "schema_invalid")):
        outcome = responses[name].outcome
        assert outcome.status == status
        assert outcome.decision is None
        assert outcome.decided_by is None


def test_the_overrides_fixture_echoes_every_override_of_the_request() -> None:
    request = DecisionRequest.model_validate_json(REQUEST.read_text(encoding="utf-8"))
    assert request.overrides is not None
    response = _responses()["overrides"]

    assert response.effective.model == request.overrides.model
    assert response.effective.cache_mode == request.overrides.cache_mode
    assert response.effective.replicate_salt == request.overrides.replicate_salt
    assert response.case_id == request.case_id


def test_the_request_example_is_contract_decision_1() -> None:
    request = DecisionRequest.model_validate_json(REQUEST.read_text(encoding="utf-8"))

    assert request.contract_version == "decision-1"
    assert request.overrides is not None


def test_build_decision_payload_reproduces_the_request_example() -> None:
    golden = json.loads(REQUEST.read_text(encoding="utf-8"))

    payload = build_decision_payload(
        "dc-001",
        {"cache_mode": "off", "replicate_salt": "r1", "model": "claude-sonnet-5-5"},
    )

    assert payload == golden
    assert DecisionRequest.model_validate(payload).case_id == "dc-001"


def test_build_decision_payload_omits_overrides_when_absent() -> None:
    assert set(build_decision_payload("dc-001", None)) == {"contract_version", "case_id"}
    assert set(build_decision_payload("dc-001", {})) == {"contract_version", "case_id"}


@pytest.mark.parametrize("path", FIXTURES, ids=lambda path: path.name)
def test_no_fixture_holds_a_key_an_auth_header_or_a_local_path(path: Path) -> None:
    text = path.read_text(encoding="utf-8")

    for forbidden in ("test-eval-key", "sk-ant-", "X-Api-Key", "carimbo-golden-cache", "/tmp/"):
        assert forbidden.lower() not in text.lower(), f"{path.name} contains {forbidden}"
    assert str(REPO_ROOT) not in text
