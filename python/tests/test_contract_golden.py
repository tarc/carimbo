"""Cross-stack contract test (API-04, D-32).

``data/contract/eval-responses/*.json`` is generated by the .NET ``GoldenResponseTests``
(``just golden``). Every file must parse with the strict models in ``carimbo_evals.contract``
(``extra="forbid"``), so an added, renamed or retyped member of the endpoint's response fails here
before any run depends on it.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pytest
from pydantic import ValidationError

from carimbo_evals.contract import EvalResponse

REPO_ROOT = Path(__file__).resolve().parents[2]
RESPONSES = REPO_ROOT / "data" / "contract" / "eval-responses"
FIXTURES = sorted(RESPONSES.glob("*.json"))


def _load(name: str) -> dict[str, Any]:
    loaded = json.loads((RESPONSES / name).read_text(encoding="utf-8"))
    assert isinstance(loaded, dict)
    return loaded


def test_there_are_golden_responses() -> None:
    assert FIXTURES, f"no fixtures under {RESPONSES}; run: just golden"


@pytest.mark.parametrize("path", FIXTURES, ids=lambda path: path.name)
def test_every_golden_response_parses_with_the_strict_models(path: Path) -> None:
    response = EvalResponse.model_validate_json(path.read_text(encoding="utf-8"))

    assert response.contract_version == "3"


def test_an_extra_top_level_member_is_rejected() -> None:
    body = _load("success.json")
    body["surprise"] = 1

    with pytest.raises(ValidationError) as caught:
        EvalResponse.model_validate_json(json.dumps(body))

    assert "surprise" in str(caught.value)


def test_an_extra_member_inside_an_attempt_is_rejected() -> None:
    body = _load("success.json")
    body["attempts"][0]["surprise"] = 1

    with pytest.raises(ValidationError) as caught:
        EvalResponse.model_validate_json(json.dumps(body))

    assert "surprise" in str(caught.value)


def test_a_missing_member_is_rejected() -> None:
    body = _load("success.json")
    del body["cost_usd"]

    with pytest.raises(ValidationError) as caught:
        EvalResponse.model_validate_json(json.dumps(body))

    assert "cost_usd" in str(caught.value)
