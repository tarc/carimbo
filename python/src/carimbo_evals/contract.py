"""Hand-written models of eval contract 3 (D-29, D-32).

The fixtures they parse are generated by the .NET tests (``just golden``). The models are strict
(``extra="forbid"``), so an added, renamed or retyped member of the endpoint's response
fails pytest.
Money is a decimal string or ``None``. Every member is required, and nullable where the endpoint
writes ``null``, so a dropped member fails as well.
"""

from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, ConfigDict

from carimbo_models.generated import Invoice

OutcomeStatus = Literal[
    "success",
    "validation_failed",
    "refused",
    "truncated",
    "schema_invalid",
    "infrastructure_failure",
]
AttemptKind = Literal["initial", "repair"]
Severity = Literal["error", "warning"]
CacheMode = Literal["off", "read_write", "read_only", "refresh"]
CacheStatus = Literal["hit", "miss", "refresh"]


class _Strict(BaseModel):
    model_config = ConfigDict(extra="forbid", strict=True)


class Usage(_Strict):
    input_tokens: int
    output_tokens: int
    cache_read_tokens: int
    cache_write_5m_tokens: int
    cache_write_1h_tokens: int


class Finding(_Strict):
    field: str
    rule_id: str
    expected: str
    actual: str
    severity: Severity


class Failure(_Strict):
    kind: str
    http_status: int | None
    request_id: str | None
    message: str


class CacheInfo(_Strict):
    mode: CacheMode
    status: CacheStatus
    key: str
    stored: bool


class Effective(_Strict):
    model: str
    prompt_version: str
    repair_prompt_version: str
    max_repairs: int
    schema_sha256: str
    pricing_version: str
    reference_date: str
    cache_mode: CacheMode
    replicate_salt: str | None


class Outcome(_Strict):
    status: OutcomeStatus
    invoice: Invoice | None
    findings: list[Finding]
    failure: Failure | None
    raw_output: str | None


class Attempt(_Strict):
    index: int
    kind: AttemptKind
    prompt_version: str
    status: OutcomeStatus
    raw_output: str | None
    invoice: Invoice | None
    findings: list[Finding]
    usage: Usage | None
    cost_usd: str | None
    cost_warning: str | None
    latency_ms: int | None
    stop_reason: str | None
    model_returned: str | None
    provider_message_id: str | None
    http_attempts: int | None
    failure: Failure | None
    cache: CacheInfo | None
    incurred_cost_usd: str | None


class EvalResponse(_Strict):
    contract_version: Literal["3"]
    case_id: str
    trace_id: str
    effective: Effective
    outcome: Outcome
    attempts: list[Attempt]
    usage: Usage
    cost_usd: str | None
    cost_warning: str | None
    latency_ms: int
    stop_reason: str | None
    model_returned: str | None
    provider_message_id: str | None
    incurred_cost_usd: str | None


class Document(_Strict):
    media_type: Literal["application/pdf"]
    content_base64: str


class Overrides(_Strict):
    """Every member is optional on the wire; the runner sends only the ones it was given."""

    model: str | None = None
    prompt_version: str | None = None
    max_repairs: int | None = None
    cache_mode: CacheMode | None = None
    replicate_salt: str | None = None


class EvalRequest(_Strict):
    contract_version: Literal["3"]
    case_id: str
    document: Document
    reference_date: str | None = None
    overrides: Overrides | None = None
